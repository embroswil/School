// L'interface est ecrite en francais ; en anglais, chaque texte affiche est remplace
// par sa traduction au moment ou il apparait a l'ecran (dictionnaire + quelques
// formules avec des nombres). Les dates et les nombres passent au format anglais.
const CLE = 'school-langue'

export const langue = (() => {
  try {
    const l = localStorage.getItem(CLE)
    if (l === 'fr' || l === 'en') return l
  } catch (_) {}
  return /^en\b/i.test(navigator.language || '') ? 'en' : 'fr'
})()

export function changerLangue(l) {
  try {
    localStorage.setItem(CLE, l)
  } catch (_) {}
  window.location.reload()
}

