const CLE = 'school-langue'

export const langue = (() => {
  try {
    const l = localStorage.getItem(CLE)
    if (l === 'fr' || l === 'en') return l
  } catch (_) {}
  return /^en\b/i.test(navigator.language || '') ? 'en' : 'fr'
})()

export function changerLangue(l) {
  try {
    localStorage.setItem(CLE, l)
  } catch (_) {}
  window.location.reload()
}

