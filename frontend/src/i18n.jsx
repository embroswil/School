export const traduire = (texte) => {
  if (langue !== 'en' || !texte) return texte
  const t = texte.trim()
  if (!t) return texte
  const direct = EN[t] || EN[t.replace(/\s+/g, ' ')]
  if (direct) return texte.replace(t, direct)
  for (const [motif, remplacement] of FORMULES) if (motif.test(t)) return texte.replace(t, t.replace(motif, remplacement))
  return texte
}

const IGNORER = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE'])
const ATTRIBUTS = ['placeholder', 'aria-label', 'title', 'alt']

function traduireNoeud(n) {
  if (n.nodeType === 3) {
    const p = n.parentNode
    if (!p || IGNORER.has(p.nodeName) || p.closest?.('[data-brut]')) return
    const v = traduire(n.nodeValue)
    if (v !== n.nodeValue) n.nodeValue = v
    return
  }
  if (n.nodeType !== 1 || IGNORER.has(n.nodeName) || n.hasAttribute?.('data-brut')) return
  for (const a of ATTRIBUTS) {
    const v = n.getAttribute(a)
    if (v) {
      const t = traduire(v)
      if (t !== v) n.setAttribute(a, t)
    }
  }
  for (const c of n.childNodes) traduireNoeud(c)
}

// Mise en route : uniquement en anglais
export function demarrerTraduction() {
  document.documentElement.lang = langue
  if (langue !== 'en') return
  // Dates et nombres au format anglais
  const vers = (l) => (l === 'fr-FR' || l === 'fr' || l === undefined ? 'en-GB' : l)
  const d = Date.prototype
  const [ld, ls, lt] = [d.toLocaleDateString, d.toLocaleString, d.toLocaleTimeString]
  d.toLocaleDateString = function (l, o) {
    return ld.call(this, vers(l), o)
  }
  d.toLocaleString = function (l, o) {
    return ls.call(this, vers(l), o)
  }
  d.toLocaleTimeString = function (l, o) {
    return lt.call(this, vers(l), o)
  }
  const nl = Number.prototype.toLocaleString
  Number.prototype.toLocaleString = function (l, o) {
    return nl.call(this, vers(l), o)
  }
  document.title = 'School'
  const observer = new MutationObserver((mutations) => {
    for (const m of mutations) {
      if (m.type === 'characterData') traduireNoeud(m.target)
      else if (m.type === 'attributes') traduireNoeud(m.target)
      else m.addedNodes.forEach(traduireNoeud)
    }
  })
  const lancer = () => {
    traduireNoeud(document.body)
    observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRIBUTS })
  }
  if (document.body) lancer()
  else document.addEventListener('DOMContentLoaded', lancer)
  // Confirmations du navigateur
  const conf = window.confirm.bind(window)
  window.confirm = (m) => conf(traduire(m))
  const al = window.alert.bind(window)
  window.alert = (m) => al(traduire(m))
  const pr = window.prompt.bind(window)
  window.prompt = (m, v) => pr(traduire(m), v)
}

// Petit selecteur de langue (FR | EN)
export function ChoixLangue({ style }) {
  return (
    <span className="choix-langue" style={style} data-brut>
      <button type="button" aria-pressed={langue === 'fr'} onClick={() => langue !== 'fr' && changerLangue('fr')}>
        FR
      </button>
      <button type="button" aria-pressed={langue === 'en'} onClick={() => langue !== 'en' && changerLangue('en')}>
        EN
      </button>
    </span>
  )
}

// Drapeau a cote de la cloche : touche pour passer en anglais / en francais
export function DrapeauLangue() {
  const autre = langue === 'en' ? 'fr' : 'en'
  return (
    <button
      type="button"
      className="icon-btn drapeau"
      data-brut
      onClick={() => changerLangue(autre)}
      aria-label={langue === 'en' ? 'Passer en français' : 'Switch to English'}
      title={langue === 'en' ? 'Français' : 'English'}
    >
      <span aria-hidden="true">{langue === 'en' ? '🇬🇧' : '🇫🇷'}</span>
      <small>{langue.toUpperCase()}</small>
    </button>
  )
}
